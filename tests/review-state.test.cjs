const assert = require('node:assert/strict');
const m = require('../review-state.js');
const ids = ['a','b','c','d','e'];
let state = m.reconcile(ids, null);
assert.deepEqual(m.active(state), ids);
state = m.remove(state, ['b','d']);
assert.deepEqual(m.active(state), ['a','c','e']);
state = m.move(state, ['e'], 0);
assert.deepEqual(m.active(state), ['e','a','c']);
state = m.move(state, ['e'], 2);
assert.deepEqual(m.active(state), ['a','c','e']);
state = m.restore(state, ['b']);
assert.equal(m.active(state).includes('b'), true);
assert.equal(m.active(state).includes('d'), false);
const persisted = JSON.parse(JSON.stringify(state));
assert.deepEqual(m.reconcile(ids, persisted), state);
const expanded = m.reconcile(['a','new','b','c','d','e'], persisted);
assert.equal(expanded.order[expanded.order.indexOf('a') + 1], 'new');
assert.deepEqual(expanded.deleted, ['d']);
assert.deepEqual(m.active(m.move(m.reconcile(ids), ['b','c'], 3)), ['a','d','e','b','c']);
assert.deepEqual(m.importState({format:'gisday-santaclara-review',version:1,...state}, ids), state);
assert.throws(() => m.importState({order:['a']}, ids));
assert.throws(() => m.importState({format:'gisday-santaclara-review',version:1,order:['unknown'],deleted:[]}, ids));
assert.deepEqual(m.active(m.remove(m.reconcile(ids), ids)), []);
assert.equal(new Set(m.reconcile(ids, {order:['b','b','unknown'],deleted:['b','unknown']}).order).size, ids.length);
console.log('Passed: remove, restore, block moves, persistence, source updates, import validation, empty deck.');
const custom = {id:'title-test',text:'A map of memory',emphasis:'memory',fontSize:140,textColor:'#777777',emphasisColor:'#ffffff',section:'Titles'};
const withTitle = m.title(m.reconcile(ids), custom, 2);
assert.deepEqual(m.active(withTitle), ['a','b','title-test','c','d','e']);
assert.equal(withTitle.titles['title-test'].fontSize, 140);
const titleReloaded = m.reconcile(ids, JSON.parse(JSON.stringify(withTitle)));
assert.deepEqual(titleReloaded, withTitle);
const titleRemoved = m.remove(withTitle, ['title-test']);
assert.equal(titleRemoved.titles['title-test'].text, 'A map of memory');
assert.deepEqual(m.restore(titleRemoved, ['title-test']), withTitle);
assert.deepEqual(m.importState({format:'gisday-santaclara-review',version:1,...withTitle}, ids), withTitle);
assert.equal(m.move(withTitle,['title-test'],0).titles['title-test'].fontSize,140);
const titleUpdated = m.title(withTitle,{...custom,text:'New words',fontSize:500},0);
assert.equal(titleUpdated.order.length, withTitle.order.length);
assert.equal(titleUpdated.titles['title-test'].fontSize,200);
assert.deepEqual(m.range(ids,'b','e'),['b','c','d','e']);
assert.deepEqual(m.range(ids,'d','a'),['a','b','c','d']);
assert.deepEqual(m.range(ids,'unknown','a'),[]);
assert.throws(()=>m.title(withTitle,{id:'title-empty',text:' '},0));
console.log('Passed: title insertion, editing, sizing, reload, remove/restore, move, export/import, and range selection.');
